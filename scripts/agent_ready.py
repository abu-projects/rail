"""Build public agent resources from the same content as the website."""
from pathlib import Path
from html.parser import HTMLParser
from hashlib import sha256
import json
import re
from urllib.parse import urljoin

ORIGIN = 'https://railcycles.ch'


class Markdown(HTMLParser):
    def __init__(self, page_url):
        super().__init__(convert_charrefs=True)
        self.page_url = page_url
        self.parts, self.main, self.skip, self.links = [], False, 0, []

    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        if tag == 'main': self.main = True
        if not self.main: return
        if tag in ('script', 'style', 'svg', 'form'): self.skip += 1
        if self.skip: return
        if tag in ('h1', 'h2', 'h3', 'h4'): self.parts.append('\n\n' + '#' * int(tag[1]) + ' ')
        elif tag in ('p', 'section', 'article', 'figure', 'div'): self.parts.append('\n\n')
        elif tag == 'li': self.parts.append('\n- ')
        elif tag == 'br': self.parts.append('\n')
        elif tag == 'a':
            self.parts.append('[')
            self.links.append(urljoin(self.page_url, attrs.get('href', '')))

    def handle_endtag(self, tag):
        if tag == 'main': self.main = False
        if not self.main: return
        if tag in ('script', 'style', 'svg', 'form') and self.skip:
            self.skip -= 1
            return
        if self.skip: return
        if tag == 'a' and self.links: self.parts.append('](' + self.links.pop() + ')')
        if tag in ('p', 'h1', 'h2', 'h3', 'h4', 'section', 'article'): self.parts.append('\n\n')

    def handle_data(self, data):
        if self.main and not self.skip: self.parts.append(re.sub(r'\s+', ' ', data))


def build(root, routes, models, specs, prices, copy):
    def write(path, data):
        target = root / path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(json.dumps(data, ensure_ascii=False, indent=2) + '\n' if not isinstance(data, str) else data)
    pages = []
    for lang, mapping in routes.items():
        for page, filename in mapping.items():
            if page == 'not_found': continue
            path = ('en/' if lang == 'en' else '') + filename
            route = '/' + (('en/' if lang == 'en' else '') if page == 'home' else path.removesuffix('.html'))
            parser = Markdown(ORIGIN + route)
            parser.feed((root / path).read_text())
            text = re.sub(r'\n[ \t]+', '\n', ''.join(parser.parts))
            text = re.sub(r'[ \t]+$', '', text, flags=re.MULTILINE)
            text = re.sub(r'\n{3,}', '\n\n', text).strip()
            markdown = f'Source: {ORIGIN}{route}\nLanguage: {lang}\n\n{text}\n'
            write('agent/pages/' + path.removesuffix('.html') + '.md', markdown)
            pages.append({'language': lang, 'page': page, 'url': ORIGIN + route,
                          'markdown': ORIGIN + '/agent/pages/' + path.removesuffix('.html') + '.md'})
    catalog = {'name': 'RAIL Cycles', 'region': 'Central Switzerland', 'founder': 'Sam',
               'languages': ['de-CH', 'en'], 'pages': pages, 'models': []}
    for slug, name, category in models:
        notes = {lang: copy[lang]['price_note'] for lang in copy}
        if slug in ('lopper', 'muetterschwandenberg'):
            notes['de'] = notes['de'].replace('Rahmen,', 'Rahmen ohne Federbein,')
        if slug == 'muetterschwandenberg':
            notes['en'] = notes['en'].replace('excluding VAT', 'excluding rear shock and VAT')
        catalog['models'].append({'id': slug, 'name': name, 'category': category,
            'url': ORIGIN + '/en/models#' + slug,
            'specifications': {lang: specs[lang][slug][0] for lang in specs},
            'frameGuidePrice': {'amount': int(prices[slug].replace('’', '')), 'currency': 'CHF',
                               'includesVAT': False, 'note': notes['en'], 'localizedNotes': notes}})
    write('agent/catalog.json', catalog)
    write('functions/_catalog.js', '// Generated by scripts/agent_ready.py.\nexport default ' + json.dumps(catalog, ensure_ascii=False) + ';\n')
    write('openapi.json', {'openapi': '3.1.0', 'info': {'title': 'RAIL public catalog', 'version': '1.0.0',
        'description': 'Read-only public bicycle models and website resources. No account required.'},
        'servers': [{'url': ORIGIN}], 'paths': {'/api/catalog': {'get': {'operationId': 'getRailCatalog',
        'summary': 'Read public bicycle models, guide prices and page links', 'security': [],
        'responses': {'200': {'description': 'Public RAIL catalog', 'content': {'application/json': {'schema': {'type': 'object'}}}}}}}}})
    write('agent/api.md', '# RAIL public catalog API\n\nGET https://railcycles.ch/api/catalog returns the public models, frame guide prices (CHF, excluding VAT), specifications and bilingual page links as JSON. No authentication is required. Prices are guides, not quotes; confirm with Sam using the website contact page.\n\nThe read-only MCP endpoint is https://railcycles.ch/mcp. Its `get_rail_catalog` tool returns the same public data. No tool submits enquiries or orders.\n')
    write('auth.md', '# Access to RAIL public information\n\nNo registration, account, API key or OAuth flow is required for the public website, GET https://railcycles.ch/api/catalog or the read-only MCP tool at https://railcycles.ch/mcp.\n\nThe only agent tool is `get_rail_catalog`. It reads published models, frame guide prices, specifications and page links. There are no protected agent APIs, personal account data, ordering tools or automated enquiry tools.\n\nTo make an enquiry, open https://railcycles.ch/en/contact and review the message before submitting. Sending an enquiry requires the person’s explicit approval.\n')
    write('.well-known/api-catalog', {'linkset': [{'anchor': ORIGIN + '/api/catalog',
        'service-desc': [{'href': ORIGIN + '/openapi.json', 'type': 'application/vnd.oai.openapi+json'}],
        'service-doc': [{'href': ORIGIN + '/agent/api.md', 'type': 'text/markdown'}]}]})
    # Poppy 0.1 section 3.1 permits ordinary signed-out browsing without auth.
    # Listing APIs here would instead promise Poppy sessions and an OAuth issuer.
    write('.well-known/poppy.json', {'protocol_version': '0.1',
        'organization': {'name': 'RAIL Cycles', 'domain': 'railcycles.ch'}, 'web': {}})
    skill = '''---
name: rail-cycles-catalog
description: Find RAIL handmade bicycle models, specifications, guide prices and official bilingual pages.
---

# RAIL Cycles public catalog

Read https://railcycles.ch/api/catalog for the current four bicycle models and bilingual page links. Alternatively use the read-only `get_rail_catalog` tool at https://railcycles.ch/mcp. Use the official page URL in answers and choose German or English as requested.

Frame guide prices are in CHF, exclude VAT and refer to finished, coated and machined frames. They are not binding quotes. Refer custom geometry, availability and final pricing questions to Sam through https://railcycles.ch/en/contact. Do not invent stock, delivery times or purchase terms. The catalog tools are read-only; never submit a contact enquiry without the person's explicit approval.
'''
    write('.well-known/agent-skills/rail-cycles-catalog/SKILL.md', skill)
    write('.well-known/agent-skills/index.json', {'$schema': 'https://schemas.agentskills.io/discovery/0.2.0/schema.json',
        'skills': [{'name': 'rail-cycles-catalog', 'type': 'skill-md', 'description': 'Read RAIL models, specifications and frame guide prices.',
                    'url': ORIGIN + '/.well-known/agent-skills/rail-cycles-catalog/SKILL.md',
                    'digest': 'sha256:' + sha256(skill.encode()).hexdigest()}]})
    write('.well-known/mcp/server-card.json', {
        '$schema': 'https://static.modelcontextprotocol.io/schemas/v1/server-card.schema.json',
        'name': 'ch.railcycles/catalog', 'version': '1.0.0',
        'title': 'RAIL Cycles public catalog', 'websiteUrl': ORIGIN,
        'remotes': [{'type': 'streamable-http', 'url': ORIGIN + '/mcp',
                     'supportedProtocolVersions': ['2025-11-25', '2025-06-18', '2025-03-26']}],
        'description': 'Read-only public RAIL bicycle catalog. No account or email submission.',
        # Compatibility with earlier server-card consumers; runtime tools/list remains authoritative.
        'serverInfo': {'name': 'ch.railcycles/catalog', 'version': '1.0.0'},
        'transport': {'type': 'streamable-http', 'endpoint': ORIGIN + '/mcp'},
        'capabilities': {'tools': {}}})
    write('.well-known/ai-catalog.json', {'specVersion': '1.0', 'host': {'displayName': 'RAIL Cycles', 'identifier': 'did:web:railcycles.ch'},
        'entries': [{'identifier': 'urn:air:railcycles.ch:api:catalog', 'displayName': 'RAIL bicycle catalog API',
                     'type': 'application/vnd.oai.openapi+json', 'url': ORIGIN + '/openapi.json',
                     'representativeQueries': ['What gravel bike does RAIL make?', 'Compare RAIL trail and enduro frame specifications', 'What are RAIL frame guide prices?']},
                    {'identifier': 'urn:air:railcycles.ch:mcp:catalog', 'displayName': 'RAIL read-only MCP catalog',
                     'type': 'application/mcp-server-card+json', 'url': ORIGIN + '/.well-known/mcp/server-card.json',
                     'representativeQueries': ['List RAIL handmade bicycle models', 'Find official RAIL model pages in German and English']}]})
